#include <iostream>
#include <vector>

int main()
{
    std::vector<int> vec = {10, 20, 30};
    int *ptr = &vec[0];
    // Вывожу значение через указатель
    if (ptr != nullptr)
    {
        std::cout << "Значение ptr: " << *ptr << std::endl;
    }

    // Добавляю 50 новых элементов в vec
    for (int i = 0; i < 50; i++)
    {
        // 30 это последнее значение будем от него отталкиваться
        // а чтобы последующий был +10 поэтому прибавил 10
        // Вектор переносится на новый участок памяти так как в старом не хватает памяти
        vec.push_back(i + 30 + 10);
    }
    // У нас сохранилася старый адресс
    std::cout << "После добавления (неопределенное поведение) " << *ptr << std::endl;
    // После перераспределения памяти ptr становится висячим
    // Обращаться через него к старому объекту нельзя

    // Вторая часть задания с реверсе
    std::vector<int> vec2 = {10, 20, 30};
    // заранее выделяем вместимость в 1000
    vec2.reserve(1000);

    int *ptr2 = &vec2[0];

    if (ptr2 != nullptr)
    {
        std::cout << "До добавления c reverse " << *ptr2 << std::endl;
    }
    // Добавляем 50 элементов
    for (int i = 0; i < 50; i++)
    {
        vec2.push_back(i + 30 + 10);
    }
    if (ptr2 != nullptr)
    {
        std::cout << "После добавления " << *ptr2 << std::endl;
    }
    return 0;
}